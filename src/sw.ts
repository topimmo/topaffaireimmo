/// <reference lib="webworker" />
import { clientsClaim } from 'workbox-core';
import { precacheAndRoute } from 'workbox-precaching';
import { registerRoute } from 'workbox-routing';
import { CacheFirst, NetworkFirst } from 'workbox-strategies';
import { ExpirationPlugin } from 'workbox-expiration';
import { CacheableResponsePlugin } from 'workbox-cacheable-response';

declare const self: ServiceWorkerGlobalScope & {
  __WB_MANIFEST: Array<{ url: string; revision: string }>;
};

// Service Worker version - increment to force update
const SW_VERSION = '1.0.2';

// Take control of all clients immediately
clientsClaim();

// Precache all assets generated by Vite PWA plugin
precacheAndRoute(self.__WB_MANIFEST);

// FIX: Bypass /admin routes to prevent offline fallback hijacking
// Admin routes must always reach the network to handle auth properly
self.addEventListener('fetch', (event: FetchEvent) => {
  const url = new URL(event.request.url);
  
  // If request is for /admin or /admin/*, bypass service worker entirely
  if (url.pathname === '/admin' || url.pathname.startsWith('/admin/')) {
    event.respondWith(fetch(event.request));
    return;
  }
});

// Runtime caching strategies (same as vite.config.ts)
// Cache images (CacheFirst)
registerRoute(
  ({ url }) => url.pathname.match(/\.(?:png|jpg|jpeg|svg|gif|webp|avif)$/i),
  new CacheFirst({
    cacheName: 'images-cache',
    plugins: [
      new ExpirationPlugin({
        maxEntries: 100,
        maxAgeSeconds: 60 * 60 * 24 * 30, // 30 days
      }),
      new CacheableResponsePlugin({
        statuses: [0, 200],
      }),
    ],
  })
);

// Supabase Storage images (CacheFirst)
registerRoute(
  ({ url }) => url.hostname.includes('supabase.co') && url.pathname.includes('/storage/v1/object/public/'),
  new CacheFirst({
    cacheName: 'supabase-images-cache',
    plugins: [
      new ExpirationPlugin({
        maxEntries: 100,
        maxAgeSeconds: 60 * 60 * 24 * 7, // 7 days
      }),
      new CacheableResponsePlugin({
        statuses: [0, 200],
      }),
    ],
  })
);

// Supabase API calls (NetworkFirst) - EXCLUDE auth endpoints
registerRoute(
  ({ url, request }) => {
    // Only cache GET requests
    if (request.method !== 'GET') return false;
    
    // Don't cache auth endpoints
    if (url.pathname.includes('/auth/')) return false;
    
    // Don't cache if has auth header
    const hasAuthHeader = request.headers.has('Authorization') || 
                         request.headers.has('apikey');
    if (hasAuthHeader) return false;
    
    // Cache Supabase REST API calls
    return url.hostname.includes('supabase.co') && 
           url.pathname.includes('/rest/');
  },
  new NetworkFirst({
    cacheName: 'supabase-api-cache',
    networkTimeoutSeconds: 10,
    plugins: [
      new ExpirationPlugin({
        maxEntries: 50,
        maxAgeSeconds: 60 * 5, // 5 minutes
      }),
      new CacheableResponsePlugin({
        statuses: [0, 200],
      }),
    ],
  })
);

// Google Fonts (CacheFirst)
registerRoute(
  ({ url }) => url.origin === 'https://fonts.googleapis.com' || 
               url.origin === 'https://fonts.gstatic.com',
  new CacheFirst({
    cacheName: 'google-fonts-cache',
    plugins: [
      new ExpirationPlugin({
        maxEntries: 10,
        maxAgeSeconds: 60 * 60 * 24 * 365, // 1 year
      }),
      new CacheableResponsePlugin({
        statuses: [0, 200],
      }),
    ],
  })
);

