/**
 * Handle push notification received event
 * Display a notification to the user
 */
self.addEventListener('push', (event: PushEvent) => {
  console.log('[Service Worker] Push notification received:', event);

  if (!event.data) {
    console.log('[Service Worker] Push event has no data');
    return;
  }

  try {
    const data = event.data.json();
    const title = data.title || 'TopAffaireImmo';
    const options: NotificationOptions = {
      body: data.body || '',
      icon: data.icon || '/icons/icon-192.png',
      badge: '/icons/icon-192.png',
      tag: data.tag || 'default',
      requireInteraction: data.requireInteraction || false,
      data: data.data || {},
      // Action buttons (optional) - Typed as any to avoid NotificationOptions type issues
    } as NotificationOptions & { actions?: Array<{ action: string; title: string }> };

    // Add actions if provided
    if (data.actions) {
      (options as any).actions = data.actions;
    }

    event.waitUntil(
      self.registration.showNotification(title, options)
    );
  } catch (error) {
    console.error('[Service Worker] Error handling push event:', error);
    
    // Fallback: show basic notification
    event.waitUntil(
      self.registration.showNotification('TopAffaireImmo', {
        body: 'Vous avez une nouvelle notification',
        icon: '/icons/icon-192.png',
      })
    );
  }
});

/**
 * Handle notification click event
 * Open the app or navigate to specific URL
 */
self.addEventListener('notificationclick', (event: NotificationEvent) => {
  console.log('[Service Worker] Notification clicked:', event);

  event.notification.close();

  // Get the URL to open from notification data
  const urlToOpen = event.notification.data?.url || '/';

  event.waitUntil(
    // Check if there's already a window open
    self.clients.matchAll({
      type: 'window',
      includeUncontrolled: true,
    }).then((clientList) => {
      // If a window is already open, focus it and navigate
      for (const client of clientList) {
        if (client.url === new URL(urlToOpen, self.location.origin).href && 'focus' in client) {
          return client.focus();
        }
      }
      
      // If no window is open, open a new one
      if (self.clients.openWindow) {
        return self.clients.openWindow(urlToOpen);
      }
    })
  );
});

